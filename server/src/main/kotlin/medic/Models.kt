package medic

import kotlinx.serialization.Serializable

@Serializable
data class RegisterRequest(
    val email: String, val password: String, val name: String = "",
    /** How the app addresses the user in Hebrew: "m", "f", or "" if not chosen. */
    val address: String = "",
    /** Where the user volunteers or works: "mda", "uh", or free text for anything else. */
    val org: String = "",
)

@Serializable
data class LoginRequest(val email: String, val password: String, val name: String = "")

@Serializable
/** [instructor] users (emails in MEDIC_INSTRUCTORS) can see every student's progress. */
@OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)
data class UserDto(
    val id: Long, val email: String, val name: String,
    @kotlinx.serialization.EncodeDefault val instructor: Boolean = false,
    @kotlinx.serialization.EncodeDefault val address: String = "",
    @kotlinx.serialization.EncodeDefault val org: String = "",
)

/** One row in the instructors' list. [mastery] = share of all course questions last answered correctly. */
@Serializable
data class StudentSummary(
    val id: Long, val name: String, val email: String,
    val answered: Int, val correct: Int, val mastery: Int,
    val attempts: Int, val examsPassed: Int, val lastExamPct: Int? = null,
    val lastActive: Long = 0, val joined: Long = 0,
    val org: String = "",
)

@Serializable
data class CategoryProgress(val id: String, val name: String, val correct: Int, val answered: Int, val total: Int)

@Serializable
data class StudentDetail(val student: StudentSummary, val categories: List<CategoryProgress>, val attempts: List<Attempt>)

@Serializable
/** Fields left null keep their current value (older apps send only the name). */
data class UpdateProfileRequest(val name: String? = null, val address: String? = null, val org: String? = null)

@Serializable
data class ChangePasswordRequest(val current: String, val new: String)

@Serializable
data class DeleteAccountRequest(val password: String)

@Serializable
data class AuthResponse(val token: String, val user: UserDto, val created: Boolean = false)

/** One answer to a question: [v] 1 = correct, 0 = wrong; [t] = epoch millis when it was answered. */
@Serializable
data class Answer(val v: Int, val t: Long)

/** A finished practice run or exam. [id] is generated by the client so runs merge without duplicates. */
@Serializable
data class Attempt(
    val id: String,
    val title: String,
    val kind: String,
    val total: Int,
    val right: Int,
    val pct: Int,
    val at: Long,
    val byCategory: Map<String, List<Int>> = emptyMap(),
)

@Serializable
data class Progress(
    val answers: Map<String, Answer> = emptyMap(),
    val attempts: List<Attempt> = emptyList(),
    val updatedAt: Long = 0,
    /** Answers and attempts older than this were wiped by "reset progress" on some device. */
    val resetAt: Long = 0,
)

@Serializable
data class ErrorDto(val error: String)

@Serializable
data class VersionDto(val version: String)

@Serializable
data class HealthDto(val status: String, val contentVersion: String, val users: Long)
