package medic

import kotlinx.serialization.Serializable

@Serializable
data class RegisterRequest(val email: String, val password: String, val name: String = "")

@Serializable
data class LoginRequest(val email: String, val password: String)

@Serializable
data class UserDto(val id: Long, val email: String, val name: String)

@Serializable
data class UpdateProfileRequest(val name: String)

@Serializable
data class ChangePasswordRequest(val current: String, val new: String)

@Serializable
data class DeleteAccountRequest(val password: String)

@Serializable
data class AuthResponse(val token: String, val user: UserDto)

/** One answer to a question: [v] 1 = correct, 0 = wrong; [t] = epoch millis when it was answered. */
@Serializable
data class Answer(val v: Int, val t: Long)

/** A finished practice run or exam. [id] is generated by the client so runs merge without duplicates. */
@Serializable
data class Attempt(
    val id: String,
    val title: String,
    val kind: String,
    val total: Int,
    val right: Int,
    val pct: Int,
    val at: Long,
    val byCategory: Map<String, List<Int>> = emptyMap(),
)

@Serializable
data class Progress(
    val answers: Map<String, Answer> = emptyMap(),
    val attempts: List<Attempt> = emptyList(),
    val updatedAt: Long = 0,
    /** Answers and attempts older than this were wiped by "reset progress" on some device. */
    val resetAt: Long = 0,
)

@Serializable
data class ErrorDto(val error: String)

@Serializable
data class VersionDto(val version: String)

@Serializable
data class HealthDto(val status: String, val contentVersion: String, val users: Long)
